import { Alert } from "@/components/ui/primitives";

/**
 * تحذير يظهر مع كل نتيجة حُسبت بجدول تحويل مؤقّت.
 * يُعرَض بصيغتين: واحدة للطالب وأخرى للأخصائي.
 */
export function ProvisionalNotice({ audience }: { audience: "student" | "specialist" }) {
  if (audience === "student") {
    return (
      <Alert tone="warning" title="نتيجة أوّلية">
        حُسبت الرتب المئينية بجدول تحويل مؤقّت لأغراض التجربة، وليس بالجدول المعياري
        الرسمي. الدرجات الخام وإجاباتك صحيحة، أما الرتب والترتيب فقد تتغيّر. ناقش
        نتيجتك مع مختص التوجيه المهني قبل بناء أي قرار عليها.
      </Alert>
    );
  }

  return (
    <Alert tone="warning" title="الجدول المعياري الرسمي غير مُدخل">
      هذه النتيجة محسوبة بجدول تحويل مؤقّت (تحويل خطّي موحّد لكل الصفوف والنوعين).
      الدرجات الخام سليمة، أما الرتب المئينية ورمز الميول فغير معتمدة. لا تعتمد النتيجة
      قبل استيراد الجداول الرسمية من الدليل.
    </Alert>
  );
}
